export const messages: Record<AppLanguage, Messages> = { ko, en };
export type TranslationKey = MessageKey;
export type TranslationValues = Record<string, string | number>;

export function translate(language: AppLanguage, key: TranslationKey, values?: TranslationValues): string {
  const template = messages[language][key];
  if (!values) return template;
  return template.replace(/\{(\w+)\}/g, (token, name: string) => String(values[name] ?? token));
}
